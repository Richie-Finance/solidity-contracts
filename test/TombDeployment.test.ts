import { expect } from "chai";
import { network } from "hardhat";
import { main as deployFoundation } from "../scripts/tomb/deploy-foundation.js";
import { main as deployPegOracle } from "../scripts/tomb/deploy-oracle.js";
import { main as deployCore } from "../scripts/tomb/deploy-core.js";
import { main as deployFarm } from "../scripts/tomb/deploy-farm.js";
import { main as deployShareOracle } from "../scripts/tomb/deploy-share-oracle.js";
import { main as deployRebateOracle } from "../scripts/tomb/deploy-rebate-oracle.js";
import { main as deployPlsOracle } from "../scripts/tomb/deploy-rebate-pls-oracle.js";
import { main as deployRedeem } from "../scripts/tomb/deploy-redeem.js";
import { main as deployRebates } from "../scripts/tomb/deploy-rebates.js";
import { main as deployZap } from "../scripts/tomb/deploy-zap.js";
import { main as genesisPools, isPoolBoundsRevert } from "../scripts/tomb/add-genesis-pools.js";
import { main as configureFarm } from "../scripts/tomb/configure-farm.js";
import { main as configureSystem } from "../scripts/tomb/configure-system.js";
import { main as configureRedeem } from "../scripts/tomb/configure-redeem.js";
import { main as configureRebates } from "../scripts/tomb/configure-rebates.js";
import { main as updateOracles } from "../scripts/tomb/update-oracles.js";
import { main as transferAdmin } from "../scripts/tomb/transfer-administration.js";

const { ethers, networkHelpers } = await network.connect();

describe("Tomb deployment and configuration scripts", () => {
  it("recognizes PulseChain empty getter reverts without hiding other RPC failures", () => {
    expect(isPoolBoundsRevert(Object.assign(new Error("execution reverted"), { code: -32000, data: undefined }))).to.equal(true);
    expect(isPoolBoundsRevert({ code: "CALL_EXCEPTION", data: "0x" })).to.equal(true);
    expect(isPoolBoundsRevert({ code: -32000, message: "rate limit exceeded" })).to.equal(false);
    expect(isPoolBoundsRevert({ code: -32000, message: "execution reverted", data: "0x1234" })).to.equal(false);
    expect(isPoolBoundsRevert({ code: "NETWORK_ERROR", message: "execution reverted" })).to.equal(false);
  });
  it("deploys, configures, operates, and transfers the complete local system", async () => {
    const saved = Object.fromEntries(Object.entries(process.env).filter(([key]) => key.startsWith("TOMB_")));
    for (const key of Object.keys(saved)) delete process.env[key];
    try {
      const [signer, admin] = await ethers.getSigners();
      const ctx = { ethers, signer };
      const start = BigInt((await ethers.provider.getBlock("latest"))!.timestamp) + 86400n;
      process.env.TOMB_START_TIME = String(start);
      process.env.TOMB_COMMUNITY_FUND = signer.address;
      const { peg, share, genesis } = await deployFoundation(ctx);
      const token = await ethers.deployContract("TombScriptToken");
      Object.assign(process.env, {
        TOMB_PEG_ADDRESS: await peg.getAddress(), TOMB_SHARE_ADDRESS: await share.getAddress(),
        TOMB_GENESIS_ADDRESS: await genesis.getAddress(), TOMB_PSM_FEE_RECIPIENT: admin.address,
      });
      const pegOraclePair = await ethers.deployContract("TombScriptPair", [await peg.getAddress(), await token.getAddress()]);
      await pegOraclePair.setReserves(ethers.parseEther("1"), ethers.parseEther("1.1"));
      process.env.TOMB_PAIR_ADDRESS = await pegOraclePair.getAddress();
      process.env.TOMB_ORACLE_PERIOD = "3600";
      process.env.TOMB_ORACLE_START_TIME = String(start - 86400n);
      const pegOracle = await deployPegOracle(ctx);
      process.env.TOMB_ORACLE_ADDRESS = await pegOracle.getAddress();
      const { treasury, boardroom } = await deployCore(ctx);
      process.env.TOMB_TREASURY_ADDRESS = await treasury.getAddress();
      process.env.TOMB_BOARDROOM_ADDRESS = await boardroom.getAddress();
      const pair = await ethers.deployContract("TombScriptPair", [await share.getAddress(), "0xA1077a294dDE1B09bB078844df40758a5D0f9a27"]);
      process.env.TOMB_SHARE_PAIR_ADDRESS = await pair.getAddress();
      process.env.TOMB_SHARE_ORACLE_START_TIME = String(start - 86400n);
      const oracle = await deployShareOracle(ctx);
      process.env.TOMB_SHARE_ORACLE_ADDRESS = await oracle.getAddress();
      const daiAddress = "0xefd766ccb38eaf1dfd701853bfce31359239f305";
      const dai = await ethers.deployContract("TombScriptToken");
      await ethers.provider.send("hardhat_setCode", [daiAddress, await ethers.provider.getCode(await dai.getAddress())]);
      const rebatePair = await ethers.deployContract("TombScriptPair", [await share.getAddress(), daiAddress]);
      await rebatePair.setReserves(ethers.parseEther("1"), ethers.parseEther("2"));
      process.env.TOMB_REBATE_SHARE_PAIR_ADDRESS = await rebatePair.getAddress();
      process.env.TOMB_REBATE_ORACLE_START_TIME = String(start - 86400n);
      const rebateOracle = await deployRebateOracle(ctx);
      process.env.TOMB_REBATE_SHARE_ORACLE_ADDRESS = await rebateOracle.getAddress();
      const wplsAddress = "0xA1077a294dDE1B09bB078844df40758a5D0f9a27";
      await ethers.provider.send("hardhat_setCode", [wplsAddress, await ethers.provider.getCode(await token.getAddress())]);
      const plsPair = await ethers.deployContract("TombScriptPair", [wplsAddress, daiAddress]);
      await plsPair.setReserves(ethers.parseEther("1"), 10n ** 14n);
      process.env.TOMB_REBATE_PLS_PAIR_ADDRESS = await plsPair.getAddress();
      process.env.TOMB_REBATE_PLS_ORACLE_START_TIME = String(start - 86400n);
      const plsOracle = await deployPlsOracle(ctx);
      process.env.TOMB_REBATE_PLS_ORACLE_ADDRESS = await plsOracle.getAddress();
      process.env.TOMB_REBATE_PLS_ENABLED = "true";
      const farm = await deployFarm(ctx);
      process.env.TOMB_FARM_ADDRESS = await farm.getAddress();
      expect(await farm.psmFeeRecipient()).to.equal(admin.address);
      expect(await farm.TOTAL_REWARDS()).to.equal(ethers.parseEther("40000"));
      expect(await farm.runningTime()).to.equal(365n * 86400n);
      expect(await farm.getGeneratedReward(start, start + 365n * 86400n)).to.equal(ethers.parseEther("40000"));
      const pools = JSON.stringify([{ token: await token.getAddress(), allocPoint: "100", depositFeeBps: 100 }]);
      process.env.TOMB_GENESIS_POOLS = pools;
      process.env.TOMB_FARM_POOLS = pools;
      process.env.TOMB_GENESIS_POOLS = JSON.stringify([{ token: await token.getAddress(), allocPoint: "100", lastRewardTime: String(start + 1n) }]);
      await expect(genesisPools(ctx)).to.be.rejectedWith("lastRewardTime is no longer supported");
      process.env.TOMB_GENESIS_POOLS = pools;
      await genesisPools(ctx);
      await genesisPools(ctx);
      expect((await genesis.poolInfo(0)).depositFeeBps).to.equal(100n);
      await expect(genesis.poolInfo(1)).to.revert(ethers);
      await configureFarm(ctx);
      await configureFarm(ctx);
      expect(await farm.poolLength()).to.equal(1n);
      await configureSystem(ctx);
      await configureSystem(ctx);
      expect(await peg.balanceOf(await genesis.getAddress())).to.equal(ethers.parseEther("40176000"));
      expect(await share.balanceOf(await farm.getAddress())).to.equal(ethers.parseEther("40000"));
      expect(await peg.operator()).to.equal(await treasury.getAddress());
      expect(await boardroom.operator()).to.equal(await treasury.getAddress());
      await token.mint(admin.address, ethers.parseEther("200"));
      await token.connect(admin).approve(await genesis.getAddress(), ethers.MaxUint256);
      await token.connect(admin).approve(await farm.getAddress(), ethers.MaxUint256);
      await genesis.connect(admin).deposit(0, ethers.parseEther("100"));
      await farm.connect(admin).deposit(0, ethers.parseEther("100"));
      await share.approve(await boardroom.getAddress(), ethers.MaxUint256);
      await boardroom.stake(ethers.parseEther("0.5"));
      await networkHelpers.time.increase(3601);
      await updateOracles(ctx);
      process.env.TOMB_PSM_ENABLED = "true";
      await configureFarm(ctx);
      expect(await farm.pegStabilityModuleFeeEnabled()).to.equal(true);
      const enabledBlock = await ethers.provider.getBlockNumber();
      delete process.env.TOMB_PSM_ENABLED;
      process.env.TOMB_PSM_FEE_BPS = "2500";
      await configureFarm(ctx);
      expect(await farm.pegStabilityModuleFeeEnabled()).to.equal(true);
      expect(await farm.pegStabilityModuleFee()).to.equal(2500n);
      const enablementChanges = await farm.queryFilter(
        farm.filters.PegStabilityModuleFeeEnabledChanged(),
        enabledBlock + 1,
      );
      expect(enablementChanges).to.have.length(0);
      await networkHelpers.time.increaseTo(start + 100n);
      await treasury.allocateSeigniorage();
      expect(await boardroom.earned(signer.address)).to.be.greaterThan(0n);
      await oracle.update();
      const cashBefore = await peg.balanceOf(admin.address);
      await genesis.connect(admin).withdraw(0, 0);
      expect(await peg.balanceOf(admin.address)).to.be.greaterThan(cashBefore);
      const pendingRich = await farm.pendingShare(0, admin.address);
      const psmFee = await farm.quotePegStabilityModuleFee(pendingRich);
      // The harvest transaction lands in a later block and accrues a little
      // more RICH, so include a buffer; Farm refunds all excess PLS.
      await farm.connect(admin).harvest(0, {
        value: psmFee + ethers.parseEther("1"),
      });
      expect(await share.balanceOf(admin.address)).to.be.greaterThan(0n);
      process.env.TOMB_PDAI_ADDRESS = await token.getAddress();
      process.env.TOMB_REDEEM_PEG_RECIPIENT = admin.address;
      const redeem = await deployRedeem(ctx);
      process.env.TOMB_REDEEM_ADDRESS = await redeem.getAddress();
      expect(await redeem.pegRecipient()).to.equal(admin.address);
      process.env.TOMB_REDEEM_PDAI_RESERVE_WEI = "1000";
      await token.mint(signer.address, 1000);
      await configureRedeem(ctx);
      await configureRedeem(ctx);
      expect(await token.balanceOf(await redeem.getAddress())).to.equal(1000n);
      const rebates = await deployRebates(ctx);
      process.env.TOMB_REBATES_ADDRESS = await rebates.getAddress();
      process.env.TOMB_REBATE_ASSETS = JSON.stringify([{ token: await token.getAddress(), multiplier: "1000000", oracle: await oracle.getAddress(), isLP: true }]);
      await expect(configureRebates(ctx)).to.be.rejectedWith("LP rebate assets are not supported");
      process.env.TOMB_REBATE_ASSETS = JSON.stringify([{ token: daiAddress, multiplier: "1000000" }]);
      process.env.TOMB_REBATE_SHARE_RESERVE_WEI = "1000";
      await configureRebates(ctx);
      await configureRebates(ctx);
      expect(await share.balanceOf(await rebates.getAddress())).to.equal(1000n);
      expect((await rebates.assets(wplsAddress)).isAdded).to.equal(true);
      const router = await ethers.deployContract("TombScriptRouter");
      await ethers.provider.send("hardhat_setCode", ["0x165C3410fC91EF562C50559f7d2289fEbed552d9", await ethers.provider.getCode(await router.getAddress())]);
      const pegPair = await ethers.deployContract("TombScriptPair", [await peg.getAddress(), "0x6B175474E89094C44Da98b954EedeAC495271d0F"]);
      process.env.TOMB_PEG_PDAI_PAIR_ADDRESS = await pegPair.getAddress();
      const factoryMock = await ethers.deployContract("TombScriptFactory");
      const factoryAddress = "0x29eA7545DEf87022BAdc76323F373EA1e707C523";
      await ethers.provider.send("hardhat_setCode", [factoryAddress, await ethers.provider.getCode(await factoryMock.getAddress())]);
      const factory = await ethers.getContractAt("TombScriptFactory", factoryAddress);
      await factory.setPair(await peg.getAddress(), "0x6B175474E89094C44Da98b954EedeAC495271d0F", await pegPair.getAddress());
      await factory.setPair(await share.getAddress(), wplsAddress, await pair.getAddress());
      const { pegZap: zap, shareZap } = await deployZap(ctx);
      process.env.TOMB_SHARE_ZAP_ADDRESS = await shareZap.getAddress();
      expect(await shareZap.TOKEN()).to.equal(await share.getAddress());
      expect(await shareZap.QUOTE()).to.equal(wplsAddress);
      expect(await shareZap.LP()).to.equal(await pair.getAddress());
      process.env.TOMB_ZAP_ADDRESS = await zap.getAddress();
      process.env.TOMB_ADMIN_ADDRESS = admin.address;
      await transferAdmin(ctx);
      await transferAdmin(ctx);
      expect(await treasury.operator()).to.equal(admin.address);
      expect(await farm.operator()).to.equal(admin.address);
      expect(await share.owner()).to.equal(admin.address);
      expect(await share.operator()).to.equal(await treasury.getAddress());
      expect(await pegOracle.owner()).to.equal(admin.address);
      expect(await oracle.owner()).to.equal(admin.address);
      expect(await rebateOracle.owner()).to.equal(admin.address);
      expect(await plsOracle.owner()).to.equal(admin.address);
      expect(await redeem.owner()).to.equal(admin.address);
      expect(await zap.owner()).to.equal(admin.address);
      expect(await shareZap.owner()).to.equal(admin.address);
    } finally {
      for (const key of Object.keys(process.env)) if (key.startsWith("TOMB_")) delete process.env[key];
      Object.assign(process.env, saved);
    }
  });
});
